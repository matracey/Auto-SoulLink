@cache
def _companion_abi(title: str) -> int | None:
    """profile.json overlay.abi of the title's pack (SLINK_ABI_VERSION, generated by tools/gen_gen2_profile.py);
    None when unreadable or not a positive integer, which refuses every hello (fail closed)."""
    try:
        with open(_DATA / f"gen2_{title}" / "profile.json", encoding="utf-8") as fh:
            abi = json.load(fh)["titles"][title]["overlay"]["abi"]
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return abi if type(abi) is int and abi > 0 else None


