    @staticmethod
    def companion_refusal(hello):
        # Owner 2026-10-02: Crystal, Gold and Silver all require the companion overlay. The evidence is the
        # mailbox ABI the cartridge's own LIVE service publishes (lua/gen2/panel.lua companion_abi), compared
        # exactly to the pinned one; the launcher's artifact_kind is a claim, never evidence, and must agree.
        rom_type = hello.get("rom_type")
        title = _TITLE_FOR_ROM_TYPE.get(rom_type)
        if title is None:
            return None
        pinned, abi = _companion_abi(title), hello.get("companion_abi")
        if pinned is None or type(abi) is not int or abi != pinned or hello.get("artifact_kind") not in _COMPANION:
            return companion_required_reason(rom_type)
        return None

