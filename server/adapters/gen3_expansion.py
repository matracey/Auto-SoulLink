"""Server facts for one pinned pokeemerald-expansion reference build.

SOURCE: expansion e8bd1cd7, extracted from ROM 28877d73 using compiler layout.
No Lua admission or runtime qualification is implied by this server adapter.
Regenerate with tools/extract_expansion_data.py --rom <reference.gba>
--source <expansion-e8bd1cd7-checkout>
--layout data/games/gen3_exp/28877d73/layout.json
--output data/games/gen3_exp/28877d73/data.json; add --check for read-only comparison.

Recorded limits: area/static-policy packs and ability prose are not extracted (trainer panels
ARE, since XC4/XC4b; wild tables ARE, since EXP-DATA-WILD -- see below). Gift areas
and the fixed-species exemption are derived from the pack's own census (see _gift_policy()); the
exemption is NOT inherited from vanilla.
Sprites use National Dex base art, not form art. This adapter only READS
expansion data/records.

Calc: calc_profile()/calc_name()/calc_stats() (XC1-XC3,
docs/gen3_emerald/research/expansion_calc_design_2026-09-26.md §4) run this
build at the vendored calc's gen 9 mechanics. calc_profile()["sets"] points at
calc/src/js/data/sets/games/EmeraldExpansion.js (XC4a), generated by
tools/gen_gen3_exp_trainers.py from src/data/trainers.h at the pin -- full
species+level coverage of every party slot (not a curated subset). A handful
of names have no gen-9 calc equivalent at all (homebrew abilities,
Mega Stones -- Gen 9 has no Mega Evolution) and stay unresolved by design;
see tools/gen_expansion_calc_names.py's EXPECTED_UNRESOLVED.

Trainer panels (XC4b): trainer_info/trainers_for_area/trainer_party/trainer_brief lazy-load
data/games/gen3_exp/28877d73/gen3_exp_trainers.json (_load_trainers_pack(), a process-wide
functools.cache -- calc_profile()/calc_name() and a Manager render never touch this pack), the
same generator's other output -- gTrainers-indexed (wire trainer_id, no offset), key trainers
flagged for the dashboard's Upcoming Key Trainers panel (gym leaders, Elite Four, Champion, the
rival, Team Aqua/Magma leaders and admins). A Vs Seeker rematch tier's area comes from the
pinned source's own gRematchTable, never a same-(class,name) guess; trainer_brief's calc_label
is the Prep tab base name (unique per trainer id -- see tools/gen_gen3_exp_trainers.py's
compute_bases()), read by server.py's _calc_trainer_label() to label a live enemy row. See
tools/gen_gen3_exp_trainers.py's docstring for extraction rules and the remaining known gaps.

Wild tables (EXP-DATA-WILD): encounter_table() lazy-loads
data/games/gen3_exp/28877d73/expansion_encounters.json (_load_encounters_pack(), a
process-wide functools.cache, a deepcopy per call) -- area_id -> method -> entries, the same
shape as the vanilla Gen 3 packs and RR's rr_encounters.json, generated by
tools/gen_gen3_exp_wild.py from the pinned src/data/wild_encounters.json. SOURCE/MODEL only:
that is the source's DECLARED table. It has NOT been read back out of the compiled ROM, so
do not call it ROM-verified. Slot weights are the pin's own `encounter_rates`/`groups`
cross-checked against gen3_frlge._WILD_METHODS; map -> area_id is the same area_map.json the
client resolves, so the pack cannot disagree with it. Still not represented here, by their own
docs as runtime overrides rather than rate tables: gWildFeebas, the Sootopolis legendary
encounter check, and map scripts' fixed encounters. Altering Cave's
VAR_ALTERING_CAVE_WILD_SET can select a later active table; this pack shows only set 0 and
reports the skipped set. FR/LG-conditional source tables are excluded from this Emerald build.
See the generator's docstring for the
config facts that bound the card (WE_OW_ENCOUNTERS FALSE, OW_TIME_OF_DAY_ENCOUNTERS FALSE,
the never-populated fifth hiddenMonsInfo pointer).

Shiny product gap: src/pokemon.c:2480-2483 at e8bd1cd7 applies
((PID_hi ^ PID_lo ^ OT_hi ^ OT_lo) < SHINY_ODDS) ^ shinyModifier;
include/constants/pokemon.h:107 pins SHINY_ODDS=8. is_shiny accepts that bit,
but shared state.py currently calls is_shiny(key) with no record. That path
can only evaluate the natural PID rule and cannot see modifier-forced shinies
(or a modifier suppressing a natural shiny). Wire integration remains OPEN.

Key contract: the same wire key Gen3Adapter uses -- two 8-hex-digit halves, "PID:OTID",
where OTID is the FULL 32-bit OT id (TID in the low 16, SID in the high 16), never a
16-bit trainer id. Any parse here, and the shiny split that reads both halves, must
keep the SID.
"""
