# data.json's id-0 rows carry sentinels, not names: SPECIES_NONE/MOVE_NONE/ITEM_NONE/
# ABILITY_NONE are "??????????", "????????", "-" and "????????" in the shipped pack.
_SENTINEL_NAME = re.compile(r"^[\s?\-]*$")


def _name(row: dict, fallback: str) -> str:
    """``row["name"]``, or `fallback` when it is missing or an id-0 sentinel.

    A sentinel is not a display name: no board may print "??????????".
    """
    name = row.get("name")
    return name if name and _SENTINEL_NAME.fullmatch(name) is None else fallback


class Gen3ExpansionAdapter(Gen3Adapter):
    def __init__(self, **kwargs):
        if kwargs.get("rom_type", ROM_TYPE) != ROM_TYPE:
            raise ValueError("expansion reference build rom_type required")
        # "emerald" here reaches only the Gen3Adapter surfaces this class overrides.
        # Expansion numbers species nationally (0..1572, NUM_SPECIES=1573) and masks
        # its record fields per layout.json, so no vanilla Emerald table is read:
        # data.json is the only source.
        super().__init__(is_rr=False, rom_type="emerald")
        self._rom_type = ROM_TYPE
        data = json.loads(PACK.read_text(encoding="utf-8"))
        if data["schema"] != 1 or data["kind"] != "expansion" or data["rom_sha1"] != ROM_SHA1:
            raise ValueError("expansion data pack identity mismatch")
        self._species = {row["id"]: row for row in data["species"]}
        self._moves = {row["id"]: row for row in data["moves"]}
        self._items = {row["id"]: row for row in data["items"]}
        self._abilities = {row["id"]: row for row in data["abilities"]}
        self._config_macros = json.loads(CONFIG_PACK.read_text(encoding="utf-8"))["macros"]
        self._calc_names = json.loads(CALC_NAMES_PACK.read_text(encoding="utf-8"))
        # Trainer pack: NOT read here -- see _load_trainers_pack()'s docstring (OMP cx-081c78d3 F8).

    @property
    def game_id(self):
        return "gen3_exp"

    def reports_box_census(self) -> bool:
        # Server data support is not an admitted client that stamps complete box scans.
        return False

    def species_name(self, species_id):
        return _name(self._species.get(species_id, {}), f"Species #{species_id}")

    def species_types(self, species_id):
        row = self._species.get(species_id)
        return tuple(row["types"]) if species_id and row else None

    def type_name(self, type_id):
        return TYPE_NAMES[type_id] if 0 <= type_id < len(TYPE_NAMES) else "???"

    def evo_family(self, species_id):
        return self._species.get(species_id, {}).get("family", species_id)

    def move_name(self, move_id):
        if not move_id:
            return ""
        return _name(self._moves.get(move_id, {}), f"Move #{move_id}")

    @staticmethod
    def pairing_kind(kind):
        # Each future build needs explicit admission; no named/companion alias.
        return kind

    @property
    def area_pack(self):
        return "gen3_exp/28877d73"

    def is_gift_area(self, area_id):
        area_id = area_id if isinstance(area_id, str) else ""
        return area_id in _gift_policy()[0] or area_id.startswith("gift_")

    def is_fixed_species_gift(self, area_id):
        # As gen3_frlge's Emerald: gift_link_area may have prefixed gift_<area>; strip it.
        area_id = area_id if isinstance(area_id, str) else ""
        return area_id.removeprefix("gift_") in _gift_policy()[1]

    def is_daycare_area(self, area_id):
        return False

    def area_display_name(self, area_id):
        # No vanilla overrides or an invented expansion area catalog -- just the same
        # words-at-every-seam fallback every other adapter with no name table falls back to
        # (OMP cx-081c78d3 F6; e.g. gen3_frlge.area_display_name).
        return humanize_area_id(area_id) if area_id else ""

    def gender_from_key(self, key, species_id):
        # src/pokemon.c:1805-1818; species.genderRatio is extracted, including forms.
        row, parsed = self._species.get(species_id), _parse_pid_otid_key(key)
        if not row or parsed is None:
            return "genderless"
        ratio = row["genderRatio"]
        if ratio == 255:
            return "genderless"
        if ratio == 254:
            return "female"
        return "female" if (parsed[0] & 255) < ratio else "male"

    def is_shiny(self, key, *, shiny_modifier=0):
        if _parse_pid_otid_key(key) is None:
            return False
        if shiny_modifier not in (0, 1):
            raise ValueError("shiny_modifier must be one bit")
        return super().is_shiny(key) ^ bool(shiny_modifier)

    def species_abilities(self, species_id):
        row = self._species.get(species_id)
        return tuple(row["abilities"]) if row else ()

    def ability_name(self, ability_id, species_id=0):
        if not ability_id:
            return ""
        return _name(self._abilities.get(ability_id, {}), f"Ability #{ability_id}")

    def ability_description(self, ability_id):
        return ""  # The extractor supplies names, not description strings.

    def item_name(self, item_id):
        if not item_id:
            return ""
        return _name(self._items.get(item_id, {}), f"Item #{item_id}")

    def move_data(self, move_id):
        row = self._moves.get(move_id)
        if not move_id or not row:
            return None
        # include/constants/pokemon.h:236-242: none=0/physical=1/special=2/status=3.
        # Display split is physical=0/special=1/status=2; never infer from type. A
        # missing or out-of-table category (0 = MOVE_STATUS_NONE is unused) takes 2:
        # the pack proves no physical/special split there, so display must not invent
        # one, and a table gap must not raise mid-page.
        return {"name": _name(row, f"Move #{move_id}"),
                "type_id": row["type"], "type_name": self.type_name(row["type"]),
                "power": row["power"], "accuracy": row["accuracy"], "pp": row["pp"],
                "split": {1: 0, 2: 1, 3: 2}.get(row.get("category"), 2)}

    def to_national_dex(self, species_id):
        return self._species.get(species_id, {}).get("national_dex", 0)

    def sprite_src(self, species_id):
        dex = self.to_national_dex(species_id)
        return f"https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/{dex}.png" if dex else ""

    def sprite_html(self, species_id, form=0):
        url = self.sprite_src(species_id)
        return f'<img class="mon-sprite" src="{escape(url, quote=True)}" alt="">' if url else ""

    def form_sprite_id(self, species_id):
        return None

    def encounter_table(self, area_id):
        """Wild tables for this build (card EXP-DATA-WILD): area_id -> method -> entries, read
        from expansion_encounters.json, which tools/gen_gen3_exp_wild.py extracts from the pinned
        src/data/wild_encounters.json. SOURCE/MODEL only -- that pack is the source's DECLARED
        table; no ROM read-back has been done, so it is not ROM-verified.

        None for a blank or unknown area, so the status payload keeps showing no wild data rather
        than an empty table. A missing pack file also returns None: that is this build's pre-card
        state (no wild table at all) and must not take the status page down. A pack that IS
        present but built from another source commit raises instead, in _load_encounters_pack().

        deepcopy per call: the pack is process-wide cached, so handing out the live dicts would let
        one caller's mutation corrupt every later read (same rule as trainer_party below).
        """
        if not area_id or not ENCOUNTERS_PACK.exists():
            return None
        return copy.deepcopy(_load_encounters_pack().get(area_id) or None)

    def rom_content_fingerprint(self, payload):
        return None  # no randomized binding: the vanilla Gen 3 table decoder never reads it

    def ingest_rom_content(self, payload):
        return None

    def trainer_info(self, trainer_id):
        trainers, _ = _load_trainers_pack()
        tr = trainers.get(trainer_id)
        return (tr["name"], tr["class"]) if tr else ("", "")

    def trainers_for_area(self, area_id):
        if not area_id:
            return []
        _, trainers_by_area = _load_trainers_pack()
        return list(trainers_by_area.get(area_id, []))

    def trainer_party(self, trainer_id):
        trainers, _ = _load_trainers_pack()
        tr = trainers.get(trainer_id)
        # deepcopy: every mon dict nests further mutable structure (ivs, moves) that `dict(m)`
        # only shallow-copies -- a caller mutating out["party"][i]["ivs"]["hp"] would otherwise
        # corrupt the functools.cache-shared pack for every trainer_party()/trainer_brief() call
        # after it (card XC4c item 5; mirrors test_gen3_frlg_trainers.py's copy-isolation check,
        # extended one level deeper for this build's always-explicit ivs).
        return copy.deepcopy(tr["party"]) if tr else []

    def trainer_brief(self, trainer_id):
        trainers, _ = _load_trainers_pack()
        tr = trainers.get(trainer_id)
        if not tr or not tr["party"]:
            return None
        out = {"name": tr["name"], "class": tr["class"], "party": copy.deepcopy(tr["party"]),
               "area": tr.get("area", "")}
        if isinstance(tr.get("level_cap"), int):
            out["level_cap"] = tr["level_cap"]
        for k in ("calc_label", "fight_label"):
            if tr.get(k):
                out[k] = tr[k]
        # Same rule as Gen3Adapter._frlg_trainer_brief (gen3_frlge.py:810-818); expansion
        # Route103/scripts.inc:23-24 (and Route110, Lilycove): MALE (0) -> May, FEMALE (1) -> Brendan.
        const = tr.get("const", "")
        if const.startswith("TRAINER_MAY_"):
            out["required_player_gender"] = 0
        elif const.startswith("TRAINER_BRENDAN_"):
            out["required_player_gender"] = 1
        return out

    def milestone_cap_for_fight_label(self, fight_label):
        return None

    def calc_name(self, kind, name):
        if not name:
            return name
        return self._calc_names.get(kind, {}).get(name, name)

    def calc_profile(self):
        latest = self._config_macros.get("GEN_LATEST", {}).get("value")
        if latest != _GEN_9:
            return None  # a build targeting another generation is not gen 9 (OMP cx-7cb40977 M1)
        for macro in _CALC_CRITICAL_MACROS:
            if self._config_macros.get(macro, {}).get("value") != latest:
                return None  # config targets a generation the calc can't express (XC1 doc)
        return {"gen": 9, "dex": "expansion",
                "sets": {"file": "EmeraldExpansion.js", "var": "CUSTOMSETDEX_EE"}}

    def calc_stats(self, detail):
        blob_hex = detail.get("blob_hex")
        if not blob_hex:
            return None
        try:
            blob = bytes.fromhex(blob_hex) if isinstance(blob_hex, str) else blob_hex
            mon = gen3_codec.decode_party_mon_masked(bytes(blob), rr=False,
                                                      layout=EXPANSION_PARTY_LAYOUT)
        except (ValueError, TypeError):
            return None

        def _short(d):
            return {"hp": d["hp"], "atk": d["attack"], "def": d["defense"],
                    "spa": d["sp_attack"], "spd": d["sp_defense"], "spe": d["speed"]}

        return {
            "ivs": _short(mon["ivs"]),
            "evs": _short(mon["evs"]),
            "stats": {"hp": mon["max_hp"], "atk": mon["attack"], "def": mon["defense"],
                      "spa": mon["sp_attack"], "spd": mon["sp_defense"], "spe": mon["speed"]},
        }

    def gym_badge_slugs(self, rom_type):
        return super().gym_badge_slugs("emerald")
