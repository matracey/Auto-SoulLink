    def decode_party_blob(self, blob, *, species_marker=None):
        """species_marker is accepted for the shared signature and ignored: Polished keeps the egg flag in
        the record (form byte bit 6) and has no species list (RAM.md §1.2 wPartySpecies absent)."""
        if isinstance(blob, str):
            _require(re.fullmatch(r"[0-9A-Fa-f]{140}", blob) is not None, "malformed 70-byte party blob")
            blob = bytes.fromhex(blob)
        mon = polished_codec.decode_party_blob(blob)
        mon["key"] = polished_codec.key(mon)
        # The species the shared state judges this mon as: a variant form's BaseData record index.
        mon["effective_species_id"] = polished_codec.effective_species(
            mon["species_id"], mon["form"])
        return mon

    def validate_party_blob(self, blob, *, key=None, species_marker=None):
        try:
            mon = self.decode_party_blob(blob)
            return (mon["species_id"] in self._species and self.is_valid_held_item(mon["held_item"])
                    and all(m == 0 or m in self._moves for m in mon["moves"])
                    and (key is None or self.is_valid_mon_key(key) and mon["key"] == key.upper()))
        except (ValueError, TypeError, KeyError):
            return False

