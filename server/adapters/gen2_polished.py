    def species_name(self, species_id, form=0):
        record = self._variant_by_record.get(species_id) if type(species_id) is int else None
        if record is not None:   # an effective id: named exactly as species_name(species, form) names it
            return f"{self._species[record['species']]['name']} ({_form_label(record)})"
        if not _integer(species_id, 1, 0x1FF) or species_id not in self._species:
            return f"#{species_id}" if type(species_id) is int else "#?"
        variant = self._variants.get((species_id, form))
        name = self._species[species_id]["name"]
        return f"{name} ({_form_label(variant)})" if variant else name

    def species_types(self, species_id, form=0):
        # Owner ruling 2026-10-04: a variant form is a DIFFERENT mon. The codec hands the shared state an
        # EFFECTIVE species id (the variant's BaseData record index, 292..337), so the type clause judges
        # Alolan Rattata on Alolan Rattata's types without state.py ever seeing a form.
        # The old "form 0 of a variant-bearing species -> None" skip is gone: it silently exempted every
        # standard/variant pair (review cx-7110b381 #1), which the effective id makes unnecessary.
        record = self._variant_by_record.get(species_id) if type(species_id) is int else None
        if record is not None:
            return tuple(record["type_ids"])
        if type(form) is int and (species_id, form) in self._variants:
            return tuple(self._variants[(species_id, form)]["type_ids"])
        return tuple(self._row(species_id, form)["type_ids"]) if species_id in self._species else None

    def evo_family(self, species_id):
        """Owner ruling 2026-10-04: a regional form is a DIFFERENT mon from its standard
        counterpart, but an evolution is the SAME mon as its pre-evolution. So the family is the
        lowest effective id in the connected component of the evolution graph over BOTH the
        variant edges (forms_index.json evolves_to) and the plain edges (evolutions.json).

        A variant with no evolution edge (31 of 46) is a singleton - never merged into its
        standard counterpart, because nothing in the graph says it should be.
        """
        if type(species_id) is not int:
            return species_id
        if self._variant_families_cache is None:
            self._variant_families_cache = self._variant_families()
        return self._variant_families_cache.get(species_id, species_id)

    def _variant_families(self) -> dict:
        """Union-find over the combined graph; plain species keep the pack's own families."""
        parent = {}

        def find(x):
            parent.setdefault(x, x)
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        def union(a, b):
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[max(ra, rb)] = min(ra, rb)

        for species, family in self._families.items():
            union(species, family)
        for record, row in self._variant_by_record.items():
            find(record)
            for target in row.get("evolves_to", []):
                tid = target["effective_species_id"]
                if tid is not None:
                    union(record, tid)
        # lowest id in each component wins, so the answer is deterministic
        lowest = {}
        for node in list(parent):
            root = find(node)
            lowest[root] = min(lowest.get(root, node), node)
        return {node: lowest[find(node)] for node in parent}

